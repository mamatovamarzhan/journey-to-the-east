-- ─────────────────────────────────────────────────────────────────────
-- Journey to the East — initial database schema.
--
-- How to apply:
--   1. Open the Supabase dashboard for the project
--   2. SQL Editor → New query → paste this whole file → Run
--   3. Verify tables appear under "Database → Tables"
--
-- All app tables enable Row-Level Security (RLS) and define explicit
-- policies. Public read access where it makes sense (stories, likes,
-- comments) so anonymous visitors can see content; everything else is
-- gated on `auth.uid() = user_id`.
-- ─────────────────────────────────────────────────────────────────────

-- Required for gen_random_uuid()
create extension if not exists "pgcrypto";


-- ─── profiles ────────────────────────────────────────────────────────
-- One row per authenticated user. Created automatically by the trigger
-- below on auth.users insert, so the application never has to create it.
create table if not exists public.profiles (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null unique references auth.users(id) on delete cascade,
  name         text,
  avatar_url   text,
  bio          text,
  email        text,
  telegram_username text,
  created_at   timestamptz not null default now()
);

alter table public.profiles enable row level security;

-- Anyone (including anon) can read profile rows — needed for story authors,
-- comment authors, etc. We do NOT expose email here (front-end omits it).
create policy "profiles are publicly readable"
  on public.profiles for select
  using (true);

create policy "users can insert their own profile"
  on public.profiles for insert
  with check (auth.uid() = user_id);

create policy "users can update their own profile"
  on public.profiles for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "users can delete their own profile"
  on public.profiles for delete
  using (auth.uid() = user_id);


-- ─── favorites ───────────────────────────────────────────────────────
-- Generic favorite table — `item_type` is "city", "itinerary", "story"
