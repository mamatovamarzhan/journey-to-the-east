-- ─── storage bucket for story cover photos ──────────────────────────
-- Run this *after* the SQL above so the public bucket exists for
-- /stories submissions. Public read so cover photos render on the
-- listing page without signed URLs.
insert into storage.buckets (id, name, public)
values ('stories', 'stories', true)
on conflict (id) do nothing;

create policy "story images are publicly readable"
  on storage.objects for select
  using (bucket_id = 'stories');

create policy "authenticated users can upload story images"
  on storage.objects for insert
  with check (bucket_id = 'stories' and auth.role() = 'authenticated');

create policy "users delete their own story images"
  on storage.objects for delete
  using (bucket_id = 'stories' and auth.uid() = owner);
