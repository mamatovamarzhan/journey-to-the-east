-- ─── bookings ────────────────────────────────────────────────────────
-- A "Confirm booking" from the AI concierge writes a row here. The
-- reference like UZ-2026-001 is generated by the API route, not the DB.
create table if not exists public.bookings (
  id                    uuid primary key default gen_random_uuid(),
  user_id               uuid not null references auth.users(id) on delete cascade,
  reference             text not null unique,
  tour_data             jsonb not null,
  full_name             text not null,
  phone                 text,
  notification_channel  text not null check (notification_channel in ('email', 'telegram', 'both')),
  status                text not null default 'pending' check (status in ('pending', 'confirmed', 'cancelled')),
  created_at            timestamptz not null default now()
);

alter table public.bookings enable row level security;

create policy "users see their own bookings"
  on public.bookings for select
  using (auth.uid() = user_id);

