-- ─── triggers ────────────────────────────────────────────────────────

-- When a new user signs up via Supabase Auth, create a matching profile.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (user_id, email, name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1))
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- Keep stories.likes_count in sync via INSERT/DELETE on story_likes.
create or replace function public.bump_story_likes()
returns trigger
language plpgsql
as $$
begin
  if (tg_op = 'INSERT') then
    update public.stories set likes_count = likes_count + 1 where id = new.story_id;
    return new;
  elsif (tg_op = 'DELETE') then
    update public.stories set likes_count = greatest(likes_count - 1, 0) where id = old.story_id;
    return old;
  end if;
  return null;
end;
$$;

drop trigger if exists story_likes_count_bump on public.story_likes;
create trigger story_likes_count_bump
  after insert or delete on public.story_likes
  for each row execute function public.bump_story_likes();


